#!/usr/bin/env python3
"""Build the two scoring matrices from the dossiers' constraint tables.

Writes matrix/physics.csv, matrix/fiction.csv and matrix/MATRIX.md. Never
hand-edit those; fix the dossier and rebuild. The register order of ids is
taken from constraints/REGISTER.md.
"""
import csv
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "matrix"
ROW = re.compile(r"^\|\s*([A-Z]{3}-\d+)\s*\|\s*([A-Z/]+)\s*\|(.*)\|\s*$")
META = {
    "Loophole": re.compile(r"\*\*Loophole:\*\*\s*(L\d)"),
    "Standing": re.compile(r"\*\*Standing:\*\*\s*(K\d)"),
    "Bill": re.compile(r"\*\*Bill:\*\*\s*([^·\n]+)"),
    "Notability": re.compile(r"\*\*Notability:\*\*\s*(N\d)"),
    "Coherence": re.compile(r"\*\*Coherence:\*\*\s*(F\d)"),
    "Causality": re.compile(r"\*\*Causality:\*\*\s*(C-[a-z]+)"),
}
LOOPHOLE_NAMES = {
    "L1": "Faster in the same space", "L2": "Move the space", "L3": "Take a shortcut",
    "L4": "Leave the manifold", "L5": "Send the message", "L6": "Not FTL",
}


def register_ids():
    ids = []
    for line in (ROOT / "constraints" / "REGISTER.md").read_text().splitlines():
        m = re.match(r"^\|\s*\[?([A-Z]{3}-\d+)\]?", line)
        if m:
            ids.append(m.group(1))
    return ids


def dossiers(kind):
    for p in sorted((ROOT / "theories" / kind).glob("*.md")):
        if p.name in ("TEMPLATE.md", "README.md"):
            continue
        t = p.read_text(encoding="utf-8")
        title = re.search(r"^# (.+)$", t, re.M).group(1).strip()
        meta = {k: (r.search(t).group(1).strip() if r.search(t) else "")
                for k, r in META.items()}
        scores = {m.group(1): m.group(2) for m in map(ROW.match, t.splitlines()) if m}
        yield p.stem, title, meta, scores


def write_csv(kind, ids, rows, metacols):
    OUT.mkdir(exist_ok=True)
    with open(OUT / f"{kind}.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["slug", "title"] + metacols + ids)
        for slug, title, meta, scores in rows:
            w.writerow([slug, title] + [meta[c] for c in metacols]
                       + [scores.get(i, "") for i in ids])


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    ids = register_ids()
    phys = list(dossiers("physics"))
    fic = list(dossiers("fiction"))
    write_csv("physics", ids, phys, ["Loophole", "Standing", "Bill"])
    write_csv("fiction", ids, fic, ["Loophole", "Notability", "Coherence", "Causality"])

    md = ["# TALARIA scoring matrices", "",
          "*Generated by `tools/build_matrix.py` from the dossiers' scoring tables. Never edit by hand.*", "",
          f"Register: {len(ids)} entries. Physics dossiers: {len(phys)}. Fiction dossiers: {len(fic)}. "
          "Full grids in `physics.csv` and `fiction.csv`.", ""]

    # Physics: bill by loophole
    md += ["## Physics: what each loophole costs", "",
           "Bill marks counted across the dossiers in each loophole class.", ""]
    rows = []
    for L in sorted(LOOPHOLE_NAMES):
        members = [d for d in phys if d[2]["Loophole"] == L]
        if not members:
            continue
        bills = Counter(b.strip() for d in members for b in d[2]["Bill"].split(","))
        standing = Counter(d[2]["Standing"] for d in members)
        rows.append([f"{L} {LOOPHOLE_NAMES[L]}", len(members),
                     ", ".join(f"{k}×{v}" for k, v in sorted(bills.items())),
                     ", ".join(f"{k}×{v}" for k, v in sorted(standing.items()))])
    md += [table(["Loophole", "Dossiers", "Bills", "Standing"], rows), ""]

    # Physics: per-dossier summary
    md += ["## Physics: every proposal", ""]
    rows = []
    for slug, title, meta, sc in sorted(phys, key=lambda d: (d[2]["Loophole"], d[0])):
        c = Counter(sc.values())
        rows.append([f"[{title}](../theories/physics/{slug}.md)", meta["Loophole"], meta["Standing"],
                     meta["Bill"], c.get("VIOLATES", 0), c.get("DODGES", 0),
                     c.get("SATISFIES", 0), c.get("SILENT", 0)])
    md += [table(["Proposal", "L", "K", "Bill", "Violates", "Dodges", "Satisfies", "Silent"], rows), ""]

    # Physics: which constraints bite most
    md += ["## Physics: which constraints bite", ""]
    rows = []
    for i in ids:
        c = Counter(sc.get(i, "") for _, _, _, sc in phys)
        rows.append([f"[{i}](../constraints/{i.lower()}.md)", c.get("VIOLATES", 0), c.get("DODGES", 0),
                     c.get("SATISFIES", 0), c.get("SILENT", 0), c.get("N/A", 0)])
    md += [table(["Constraint", "Violates", "Dodges", "Satisfies", "Silent", "N/A"], rows), ""]

    if fic:
        md += ["## Fiction: coherence by loophole", ""]
        rows = []
        for L in sorted(LOOPHOLE_NAMES):
            members = [d for d in fic if d[2]["Loophole"] == L]
            if not members:
                continue
            coh = Counter(d[2]["Coherence"] for d in members)
            cau = Counter(d[2]["Causality"] for d in members)
            rows.append([f"{L} {LOOPHOLE_NAMES[L]}", len(members),
                         ", ".join(f"{k}×{v}" for k, v in sorted(coh.items())),
                         ", ".join(f"{k}×{v}" for k, v in sorted(cau.items()))])
        md += [table(["Loophole", "Dossiers", "Coherence", "Causality"], rows), ""]
        md += ["## Fiction: every drive", ""]
        rows = []
        for slug, title, meta, sc in sorted(fic, key=lambda d: (d[2]["Loophole"], d[0])):
            c = Counter(sc.values())
            rows.append([f"[{title}](../theories/fiction/{slug}.md)", meta["Loophole"], meta["Notability"],
                         meta["Coherence"], meta["Causality"], c.get("ENGAGES", 0), c.get("RULE", 0), c.get("SILENT", 0)])
        md += [table(["Work", "L", "N", "F", "Causality", "Engages", "Rule", "Silent"], rows), ""]
        md += ["## Fiction: which constraints get engaged", ""]
        rows = []
        for i in ids:
            c = Counter(sc.get(i, "") for _, _, _, sc in fic)
            rows.append([f"[{i}](../constraints/{i.lower()}.md)", c.get("ENGAGES", 0), c.get("RULE", 0),
                         c.get("SILENT", 0), c.get("N/A", 0)])
        md += [table(["Constraint", "Engages", "Rule", "Silent", "N/A"], rows), ""]

    # The join
    md += ["## The join: physics and fiction by loophole", "",
           "For each loophole, the real proposals and the invented drives that use it, side by side.", ""]
    for L in sorted(LOOPHOLE_NAMES):
        p_ = [d for d in phys if d[2]["Loophole"] == L]
        f_ = [d for d in fic if d[2]["Loophole"] == L]
        if not p_ and not f_:
            continue
        md += [f"### {L}: {LOOPHOLE_NAMES[L]}", ""]
        bills = Counter(b.strip() for d in p_ for b in d[2]["Bill"].split(",") if b.strip())
        if bills:
            md.append("Physics bill for this loophole: " + ", ".join(f"{k}×{v}" for k, v in sorted(bills.items())) + ".")
            md.append("")
        md.append("**Physics:** " + (", ".join(f"[{t}](../theories/physics/{s}.md) ({m['Standing']})" for s, t, m, _ in p_) or "none") + "  ")
        md.append("**Fiction:** " + (", ".join(f"[{t}](../theories/fiction/{s}.md) ({m['Coherence']})" for s, t, m, _ in f_) or "none"))
        md.append("")
    (OUT / "MATRIX.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"matrix: {len(phys)} physics, {len(fic)} fiction, {len(ids)} constraints -> matrix/")


if __name__ == "__main__":
    main()
